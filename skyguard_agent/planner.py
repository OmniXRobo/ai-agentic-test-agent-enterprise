"""PARSE and PLAN: from a chat or voice instruction to concrete records, and the PREVIEW the user confirms.

Parsing uses learned, approved workflows only. A deterministic parser understands structured requests
("create 20 trips on 2026-11-20 from 06:00 every 30 minutes, routes: Dubai to Abu Dhabi, Abu Dhabi to Dubai,
buses: BUS-1, BUS-2, drivers: available"). When the local model is available it interprets free wording too, but
every value it returns must be *grounded*: it has to appear in the user's own words, be generated by the batch rules
below, or be chosen by the deterministic availability check. A value the model made up is dropped and asked for.

Records are expanded deterministically (round-robin lists, time intervals, numbering, available-resource
assignment) so the preview shows every value before anything runs.
"""

from __future__ import annotations

import datetime as _dt
import re
from typing import Any

from . import rules as rule_engine
from .guard import SYSTEM_RULES
from .llm import extract_json
from .util import AgentError, digest, norm

MAX_BATCH = 500


def workflow_params(workflow: dict[str, Any]) -> list[dict[str, Any]]:
    return list(workflow["data"].get("parameters") or [])


def _param_names(p: dict[str, Any]) -> list[str]:
    names = {p.get("name") or "", p.get("field") or "", p.get("label") or ""}
    names |= {n for n in p.get("aliases") or []}
    out = set()
    for n in names:
        n = norm(n).replace("_", " ")
        variants = {n}
        if re.search(r"\bno\b", n):
            variants.add(re.sub(r"\bno\b", "number", n))
        if re.search(r"\bnumber\b", n):
            variants.add(re.sub(r"\bnumber\b", "no", n))
        for n in variants:
            if not n:
                continue
            out.add(n)
            out.add(n + ("es" if n.endswith(("s", "x", "ch", "sh")) else "s"))
            if n.endswith("es"):
                out.add(n[:-2])
            if n.endswith("s"):
                out.add(n[:-1])
    return sorted(out, key=len, reverse=True)


def match_workflow(text: str, workflows: list[dict[str, Any]]) -> dict[str, Any] | None:
    t = norm(text)
    best, best_score = None, 0.0
    for wf in workflows:
        d = wf["data"]
        words = {w for w in re.findall(r"[a-z0-9]+", norm(f"{wf['key']} {d.get('title', '')}")) if len(w) > 2}
        entity, op = norm(d.get("entity")), norm(d.get("operation"))
        score = 0.0
        if norm(wf["key"]) in t or norm(d.get("title")) in t:
            score += 3
        if entity and re.search(rf"\b{re.escape(entity)}(e?s)?\b", t):
            score += 1.5
        if op and re.search(rf"\b{re.escape(op)}\w*\b", t):
            score += 1
        score += 0.4 * sum(1 for w in words if re.search(rf"\b{re.escape(w)}", t))
        if score > best_score:
            best, best_score = wf, score
    return best if best_score >= 1.5 else None


def match_account(text: str, accounts: list[dict[str, Any]]) -> dict[str, Any] | None:
    t = norm(text)
    for acc in sorted(accounts, key=lambda a: len(a["label"]), reverse=True):  # the most specific label first
        if norm(acc["label"]) and re.search(rf"\b(as|using|with|account)\s+(the\s+)?{re.escape(norm(acc['label']))}(?!\w)", t):
            return acc
    for acc in accounts:
        if acc.get("role_key") and re.search(rf"\b(as|using)\s+(an?\s+|the\s+)?{re.escape(norm(acc['role_key']))}(?!\w)", t):
            return acc
    return None


_DATE_RE = r"(\d{4}-\d{2}-\d{2}|\d{1,2}[/.-]\d{1,2}[/.-]\d{4})"
_TIME_RE = r"(\d{1,2}:\d{2}(?:\s?[AaPp][Mm])?)"


def parse_structured(text: str, workflow: dict[str, Any]) -> dict[str, Any]:
    """Deterministic parse of a request for one workflow. Returns {records?, batch?, unknown: [...]}"""
    params = workflow_params(workflow)
    t = text.strip()
    out: dict[str, Any] = {"fixed": {}, "lists": {}, "auto": []}
    m = re.search(r"\b(\d{1,3})\s+(?:new\s+)?[a-z]", t, re.I)
    count = int(m.group(1)) if m and re.search(r"\b(create|add|make|enter|register|book|schedule)\b", t, re.I) else None
    labels = [(n, p) for p in params for n in _param_names(p)]
    labels.sort(key=lambda x: len(x[0]), reverse=True)
    # "label: a, b and c" / "label = x" / "label is x" up to the next label or end
    label_alt = "|".join(re.escape(n) for n, _ in labels)
    if label_alt:
        # a value list also ends where another part of the request starts ("..., trip numbers starting at X",
        # "... as Entry Operator", "... on 2026-12-01", "... every 30 minutes")
        clause = (r",?\s+(?:\w+\s+)?numbers?\s+(?:starting|start|from)\b|,?\s+as\s+(?=\S)"
                  r"|,?\s+(?:on|from|at|every|starting)\s+\d")
        pat = re.compile(rf"\b({label_alt})\b\s*(?:=|:|is|are)\s*(.+?)(?=(?:[;\n]|,?\s+\b(?:{label_alt})\b\s*(?:=|:|is|are)"
                         rf"|,\s*\b(?:{label_alt})\s+[A-Za-z]*-?\d|{clause}|$))", re.I | re.S)
        for mm in pat.finditer(t):
            name = norm(mm.group(1))
            p = next(p for n, p in labels if n == name)
            raw = mm.group(2).strip().strip(".")
            values = [v.strip().strip(".") for v in re.split(r",|\s+and\s+|\|", raw) if v.strip().strip(".")]
            key = p["name"]
            if len(values) == 1 and norm(values[0]) in ("available", "any available", "auto", "automatic"):
                out["auto"].append(key)
            elif len(values) > 1:
                out["lists"][key] = values
            elif values:
                out["fixed"][key] = values[0]
    # "trip number DXB400", "bus BUS-101": a label directly followed by one code-like value
    if label_alt:
        for mm in re.finditer(rf"\b({label_alt})\s+(?!starting|start|from)([A-Za-z]*-?\d[\w-]*)\b", t, re.I):
            p = next(p for n, p in labels if n == norm(mm.group(1)))
            if p["name"] not in out["fixed"] and p["name"] not in out["lists"]:
                out["fixed"][p["name"]] = mm.group(2)
    date_p = next((p for p in params if p.get("type") == "date"), None)
    time_p = next((p for p in params if p.get("type") == "time"), None)
    if date_p and date_p["name"] not in out["fixed"]:
        dm = re.search(rf"\b(?:on|date|for)\s+{_DATE_RE}", t, re.I)
        if dm:
            out["fixed"][date_p["name"]] = dm.group(1)
    if time_p:
        tm = re.search(rf"\b(?:from|at|starting(?: at)?)\s+{_TIME_RE}", t, re.I)
        if tm and time_p["name"] not in out["fixed"]:
            out["fixed"][time_p["name"]] = tm.group(1)
        im = re.search(r"\bevery\s+(\d{1,4})\s*(min|minute|minutes|h|hour|hours)\b", t, re.I) or \
            re.search(r"\b(\d{1,4})[\s-]*(min|minute|minutes|h|hour|hours)\s+(?:interval|intervals|apart|gap)\b", t, re.I)
        if im:
            out["interval_minutes"] = int(im.group(1)) * (60 if im.group(2).lower().startswith("h") else 1)
    nm = re.search(r"\bnumbers?\s+(?:starting|start|from)\s+(?:at|from|with)?\s*([A-Za-z-]*?)(\d+)\b", t, re.I)
    num_p = next((p for p in params if p.get("numbering") or re.search(r"(number|no\b|code|ref)", norm(p.get("field") or p["name"]))), None)
    if nm and num_p:
        out["numbering"] = {"param": num_p["name"], "prefix": nm.group(1), "start": int(nm.group(2)),
                            "pad": len(nm.group(2))}
    if count:
        out["count"] = min(count, MAX_BATCH)
    return out


def parse_with_llm(llm: Any, text: str, workflows: list[dict[str, Any]], accounts: list[dict[str, Any]]) -> dict[str, Any]:
    catalogue = [{"workflow": w["key"], "title": w["data"].get("title"),
                  "parameters": [{"name": p["name"], "field": p.get("field"), "type": p.get("type", "text")}
                                 for p in workflow_params(w)]} for w in workflows]
    system = (SYSTEM_RULES + " Turn the user's request into JSON with keys: workflow (one of the given workflow ids), "
              "account (an account label or null), count (number of records or null), fixed (parameter -> value), "
              "lists (parameter -> list of values to rotate), auto (parameters to fill with available values), "
              "interval_minutes, records (list of parameter -> value objects when the user lists records "
              "individually), questions (what is missing). Use only values the user said. Never invent values.")
    user = (f"Workflows: {catalogue}\nAccounts: {[a['label'] for a in accounts]}\n"
            f"User request: {text}\nReturn only JSON.")
    reply = llm.chat([{"role": "system", "content": system}, {"role": "user", "content": user}], max_tokens=700,
                     json_mode=True)
    data = extract_json(reply)
    if not isinstance(data, dict):
        raise ValueError("not an object")
    return data


def _grounded(value: Any, text: str) -> bool:
    v = norm(value)
    return bool(v) and (v in norm(text) or v.replace(" ", "") in norm(text).replace(" ", ""))


def ground(parsed: dict[str, Any], text: str, workflow: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """Keep only model-proposed values that the user actually said (or that the batch rules will generate)."""
    names = {p["name"] for p in workflow_params(workflow)}
    dropped: list[str] = []
    out: dict[str, Any] = {"fixed": {}, "lists": {}, "auto": [], "records": []}
    for k, v in (parsed.get("fixed") or {}).items():
        if k in names and _grounded(v, text):
            out["fixed"][k] = str(v)
        elif k in names:
            dropped.append(f"{k}={v}")
    for k, vs in (parsed.get("lists") or {}).items():
        if k in names and isinstance(vs, list):
            kept = [str(v) for v in vs if _grounded(v, text)]
            dropped += [f"{k}={v}" for v in vs if not _grounded(v, text)]
            if kept:
                out["lists"][k] = kept
    out["auto"] = [a for a in (parsed.get("auto") or []) if a in names]
    for rec in (parsed.get("records") or [])[:MAX_BATCH]:
        if isinstance(rec, dict):
            clean = {k: str(v) for k, v in rec.items() if k in names and _grounded(v, text)}
            dropped += [f"{k}={v}" for k, v in rec.items() if k in names and not _grounded(v, text)]
            if clean:
                out["records"].append(clean)
    if isinstance(parsed.get("count"), int) and re.search(rf"\b{parsed['count']}\b", text):
        out["count"] = min(parsed["count"], MAX_BATCH)
    if isinstance(parsed.get("interval_minutes"), int) and re.search(rf"\b{parsed['interval_minutes']}\b", text):
        out["interval_minutes"] = parsed["interval_minutes"]
    return out, dropped


def expand(spec: dict[str, Any], workflow: dict[str, Any], *, options: dict[str, list[str]] | None = None,
           rules: list[tuple[dict[str, Any], bool]] | None = None,
           existing_bookings: list[dict[str, Any]] | None = None) -> list[dict[str, Any]]:
    """Concrete records from a parsed request (deterministic)."""
    params = workflow_params(workflow)
    if spec.get("records"):
        base = [dict(r) for r in spec["records"][:MAX_BATCH]]
        for r in base:
            for k, v in (spec.get("fixed") or {}).items():
                r.setdefault(k, v)
        records = base
    else:
        count = int(spec.get("count") or max([1, *[len(v) for v in (spec.get("lists") or {}).values()]]))
        count = max(1, min(count, MAX_BATCH))
        records = [dict(spec.get("fixed") or {}) for _ in range(count)]
        for k, values in (spec.get("lists") or {}).items():
            for i, r in enumerate(records):
                r[k] = values[i % len(values)]
        date_p = next((p for p in params if p.get("type") == "date"), None)
        time_p = next((p for p in params if p.get("type") == "time"), None)
        interval = spec.get("interval_minutes")
        if interval and time_p and records[0].get(time_p["name"]):
            t0 = rule_engine.parse_time(records[0][time_p["name"]])
            d0 = rule_engine.parse_date(records[0].get(date_p["name"])) if date_p else None
            fmt = (date_p or {}).get("format")
            if t0:
                start = _dt.datetime.combine(d0 or _dt.date.today(), t0)
                for i, r in enumerate(records):
                    at = start + _dt.timedelta(minutes=interval * i)
                    r[time_p["name"]] = at.strftime("%H:%M")
                    if date_p and d0:
                        r[date_p["name"]] = at.strftime(rule_engine.DATE_FORMATS.get(fmt or "", "%Y-%m-%d")
                                                        if fmt else _same_format(records[0][date_p["name"]], at))
        num = spec.get("numbering")
        if num:
            for i, r in enumerate(records):
                r[num["param"]] = f"{num.get('prefix', '')}{str(int(num['start']) + i).zfill(int(num.get('pad') or 1))}"
    for name in spec.get("auto") or []:
        _assign_available(records, name, (options or {}).get(name) or [], rules or [], existing_bookings or [])
    return records


def _same_format(sample: str, at: _dt.datetime) -> str:
    for fmt in rule_engine.DATE_FORMATS.values():
        try:
            _dt.datetime.strptime(str(sample).strip(), fmt)
            return at.strftime(fmt)
        except ValueError:
            continue
    return at.strftime("%Y-%m-%d")


def _assign_available(records: list[dict[str, Any]], name: str, pool: list[str],
                      rules: list[tuple[dict[str, Any], bool]], bookings: list[dict[str, Any]]) -> None:
    pool = [p for p in pool if norm(p) and not norm(p).startswith(("select", "choose", "--", "please"))]
    overlap = [r for r, _ in rules if r.get("type") == "no_overlap" and r.get("resource") == name]
    for i, rec in enumerate(records):
        if rec.get(name):
            continue
        chosen = None
        start = i % len(pool) if pool else 0
        for j in range(len(pool)):
            candidate = pool[(start + j) % len(pool)]
            trial = [dict(r) for r in records[:i]] + [{**rec, name: candidate}]
            clash = False
            for rule in overlap:
                found = rule_engine.check_batch(trial, [(rule, True)], existing_bookings=bookings)
                if found.get(len(trial) - 1):
                    clash = True
                    break
            if not clash:
                chosen = candidate
                break
        if chosen:
            rec[name] = chosen
            rec.setdefault("_auto", []).append(name)


def rules_for(kb: Any, app_id: str, workflow: dict[str, Any]) -> list[tuple[dict[str, Any], bool]]:
    """(rule, enforced) for a workflow: approved rules block, rules still under review warn."""
    out = []
    keys = set(workflow["data"].get("rules") or [])
    for e in kb.items(app_id, "rule"):
        data = e["data"]
        applies = data.get("applies_to")
        if e["key"] in keys or not applies or applies in (workflow["key"], "*"):
            if e["state"] in ("approved",):
                out.append(({**data, "name": e["key"]}, True))
            elif e["state"] in ("discovered", "ai_suggested", "awaiting_approval", "needs_revalidation"):
                out.append(({**data, "name": e["key"]}, False))
    for p in workflow_params(workflow):
        if p.get("required"):
            out.append(({"type": "required", "field": p["name"], "name": f"{p['name']} required"}, True))
    return out


def field_options(kb: Any, app_id: str, workflow: dict[str, Any]) -> dict[str, list[str]]:
    """Options learned for the workflow's dropdowns (from screen knowledge)."""
    out: dict[str, list[str]] = {}
    for p in workflow_params(workflow):
        if p.get("options"):
            out[p["name"]] = list(p["options"])
            continue
        for step in workflow["data"].get("steps", []):
            if step.get("param") == p["name"] and step.get("screen"):
                screen = kb.approved(app_id, "screen", step["screen"]) or kb.latest(app_id, "screen", step["screen"])
                for f in (screen or {}).get("data", {}).get("fields", []):
                    if norm(f.get("label")) == norm(step.get("target")) and f.get("options"):
                        out[p["name"]] = [o for o in f["options"] if o]
    return out


def build_preview(*, app: dict[str, Any], stages: list[dict[str, Any]], records: list[dict[str, Any]],
                  findings: dict[int, list[dict[str, Any]]], rules: list[tuple[dict[str, Any], bool]],
                  inspection: dict[str, Any], warnings: list[str]) -> dict[str, Any]:
    rows = []
    for i, rec in enumerate(records):
        f = findings.get(i, [])
        rows.append({"seq": i + 1, "values": {k: v for k, v in rec.items() if not k.startswith("_")},
                     "auto_assigned": rec.get("_auto", []), "findings": f,
                     "status": "blocked" if rule_engine.blocking(f) else ("warning" if f else "ready")})
    ready = sum(1 for r in rows if r["status"] != "blocked")
    commit_stages = [s for s in stages if s.get("commits", True)]
    preview = {
        "application": app["name"], "environment": app.get("environment", ""), "mode": app.get("mode"),
        "stages": [{k: s.get(k) for k in ("title", "workflow", "workflow_version", "account", "login_id",
                                          "role_claimed", "role_verified", "identity_verified", "page",
                                          "expected_status", "commits")} for s in stages],
        "records": rows,
        "rules": [{"name": r.get("name") or r.get("type"), "type": r.get("type"), "enforced": en} for r, en in rules],
        "inspection": inspection,
        "warnings": warnings,
        "totals": {"records": len(rows), "ready": ready, "blocked": len(rows) - ready,
                   "operations": ready * max(1, len(commit_stages))},
    }
    preview["hash"] = digest({k: v for k, v in preview.items() if k != "hash"})
    return preview


def require(cond: bool, code: str, message: str, status: int = 400) -> None:
    if not cond:
        raise AgentError(code, message, status)
